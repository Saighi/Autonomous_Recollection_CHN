# %% [markdown]
# # Recovery Capacity Analysis - Multiple Correlations
#
# ## Overview
#
# This script analyzes the **autonomous recovery (AR) capacity** of Continuous Hopfield
# Networks (CHN) after sleep-based consolidation. It determines the maximum number of
# patterns (K) a network of size N can reliably store and recover, as a function of
# pattern correlation (rho).
#
# ## What is Autonomous Recovery?
#
# During "sleep", networks are initialized from a neutral state (all units at 0.5) and
# allowed to evolve according to their trained dynamics with diagonal inhibition. The
# network spontaneously retrieves stored patterns one by one. A simulation is considered
# **successful** if all K patterns are retrieved before any spurious attractor is visited.
#
# ## Analysis Pipeline
#
# ### Part 1: Autonomous Recovery Analysis
#
# 1. **Load sleep simulation data** from CSV containing results across:
#    - Network sizes (N): ranging from small to large
#    - Number of patterns (K): varying load levels
#    - Pattern correlations (rho): 0.1, 0.25, 0.5, 0.75, 1.0
#
# 2. **Compute success rates** for each (N, K, rho) configuration:
#    - Success = all patterns found before spurious attractor
#    - Rate = fraction of repetitions that succeed
#
# 3. **Determine recovery capacity** at 90% threshold:
#    - For each (N, rho), find max K where success rate >= 90%
#    - This defines the "reliable" retrieval after storage capacity
#
# 4. **Generate visualizations**:
#    - 2x5 heatmap grid: success rates and retrieval speed per correlation
#    - Capacity curves: max K vs N for each correlation (B&W and colored)
#
# ### Part 2: Partial Cue Query Analysis
#
# For configurations that achieved >= 90% AR success, we test **partial cue retrieval**:
# networks are given incomplete patterns (only a fraction of units informed) and must
# recover the full pattern.
#
# **Key finding**: In the load regime allowing 90% successful AR, networks can recover
# patterns with as little as **10% informed units** (90% masked). Recovery succeeds as
# long as the partial cue has a smaller Hamming distance to the target pattern than to
# other stored patterns - demonstrating robust attractor basins.
#
# ## Data Sources
#
# - **Sleep results**: `Fig_load_SR_many_correlation_diag_inh_sleep/all_simulation_data.csv`
# - **Query results**: `partial_cue_correlations/all_simulation_data.csv`
#   (generated by `run_partial_cue_queries.py`)
#
# ## Output Figures
#
# 1. `recovery_capacity_correlations_heatmap.png` - 2x5 grid showing AR success rates
#    and retrieval iterations, with 90% threshold marked by stars
# 2. `recovery_capacity_correlations_line.png` - Capacity curves (B&W, publication style)
# 3. `recovery_capacity_correlations_line_colored.png` - Capacity curves (colored)
# 4. `partial_cue_recovery_5x4_heatmap.png` - Query success for different informed fractions

