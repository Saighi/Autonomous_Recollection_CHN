# %% [markdown]
# ## Partial Cue Query Analysis
#
# ### Motivation
#
# Beyond autonomous recovery (starting from neutral state), we want to understand how
# well trained networks perform **cued retrieval** - recovering a full pattern when
# given only partial information. This is analogous to pattern completion in biological
# memory systems.
#
# ### Methodology
#
# For each stored pattern in networks that achieved >= 90% AR success:
# 1. Construct a **partial cue** by keeping only `informed_fraction` of units at their
#    pattern values and setting the rest to neutral (0.5)
# 2. Initialize network with this partial cue
# 3. Let dynamics evolve (with noise, without inhibition)
# 4. Check if network converges to the correct pattern (winner-take-all comparison)
#
# ### Tested Informed Fractions
#
# We sweep over informed fractions from 20% down to as low as 2%:
# - 20% informed = 80% of units masked (set to neutral 0.5)
# - 10% informed = 90% masked
# - 5% informed = 95% masked
# - 2% informed = 98% masked
#
# ### Key Results
#
# In the load regime that allows 90% successful autonomous recovery, networks demonstrate
# remarkable pattern completion ability. With only **10% of units informed**, networks
# reliably recover the correct pattern. The critical factor is that the partial cue must
# correlate more strongly with the target pattern than with other stored patterns (i.e.,
# have a smaller Hamming distance). This confirms that the trained attractor basins are
# deep and well-separated.
#
# ### Visualization
#
# The 5x4 heatmap grid shows query success rates:
# - **Rows**: 5 correlation values (rho = 0.1 to 1.0)
# - **Columns**: 4 informed fractions (20%, 10%, 5%, 2%)
# - **Color**: Query success rate (0-100%)
# - **Grey cells**: Configurations below 90% AR threshold (not tested)

# %% Configuration for query analysis
TRAINED_NETWORKS_DIR = Path("/home/saighi/Desktop/AR_final/Autonomous_Recollection_CHN/simulations/main_write_sleep/data/trained_networks/Fig_load_SR_many_correlation_diag_inh")
QUERY_RESULTS_DIR = Path(__file__).parent.parent.parent / "data" / "query_results" / "partial_cue_correlations"
INFORMED_FRACTIONS = [0.2, 0.1, 0.05, 0.02]  # Fraction of units that keep pattern info

# %% Build mapping from (network_size, num_patterns, noise_level) -> trained network paths
print("\n" + "=" * 70)
print("BUILDING TRAINED NETWORK INDEX")
print("=" * 70)

from utils import read_parameters

trained_network_index = {}  # (network_size, num_patterns, noise_level) -> path

if TRAINED_NETWORKS_DIR.exists():
    for sim_dir in sorted(TRAINED_NETWORKS_DIR.iterdir()):
        if sim_dir.is_dir() and sim_dir.name.startswith("sim_nb_"):
            params_file = sim_dir / "parameters.data"
            if params_file.exists():
                params = read_parameters(params_file)
                key = (
                    int(params.get("network_size", 0)),
                    int(params.get("num_patterns", 0)),
                    params.get("noise_level", 0)
                )
                trained_network_index[key] = str(sim_dir)

print(f"Indexed {len(trained_network_index)} trained networks")

# %% Identify configurations with 90% success (eligible for query testing)
# Build eligibility directly from success_rates_all (no trained network check needed)
eligible_configs = set()

for corr in correlations_to_plot:
    subset = success_rates_all[
        (success_rates_all['noise_level'] == corr) &
        (success_rates_all['success_rate'] >= SUCCESS_THRESHOLD)
    ]
    for _, row in subset.iterrows():
        key = (int(row['network_size']), int(row['num_patterns']), corr)
        eligible_configs.add(key)

print(f"Found {len(eligible_configs)} configurations with >= {SUCCESS_THRESHOLD:.0%} success")

# %% Check if query results exist
query_csv_path = QUERY_RESULTS_DIR / "all_simulation_data.csv"

if query_csv_path.exists():
    print(f"\nLoading existing query results from: {query_csv_path}")
    query_df = pd.read_csv(query_csv_path)
    print(f"Loaded {len(query_df)} query results")
else:
    print(f"\nQuery results not found at: {query_csv_path}")
    print("Run scripts/recovery_capacity/run_partial_cue_queries.py first to generate query results.")
    query_df = None

# %% Build eligibility mask (configurations with >= 90% AR success)
# Create a 2D mask for each correlation: True = eligible (>= 90% success)
eligibility_masks = {}

print("\nBuilding eligibility masks...")
for corr in correlations_to_plot:
    mask = np.zeros((len(all_num_patterns), len(all_net_sizes)), dtype=bool)
    for i, np_val in enumerate(all_num_patterns):
        for j, ns_val in enumerate(all_net_sizes):
            key = (int(ns_val), int(np_val), corr)
            mask[i, j] = key in eligible_configs
    eligibility_masks[corr] = mask
    print(f"  rho={corr}: {mask.sum()} eligible cells (out of {mask.size})")

print(f"Eligibility masks built for {len(eligibility_masks)} correlations")

# %% Generate 5x4 heatmap grid if query results exist
if query_df is not None:
    print("\n" + "=" * 70)
    print("CREATING PARTIAL CUE HEATMAP (5x4 grid)")
    print("=" * 70)

    n_rows = len(correlations_to_plot)
    n_cols = len(INFORMED_FRACTIONS)

    # Prepare data structure for heatmaps
    # For each (correlation, informed_fraction), create pivot table
    query_pivots = {}

    for corr in correlations_to_plot:
        for inf in INFORMED_FRACTIONS:
            # Filter query results for this configuration
            # Note: CSV column is still 'informed_fraction' after C++ update
            subset = query_df[
                (query_df['noise_level'] == corr) &
                (np.isclose(query_df['informed_fraction'], inf, atol=0.001))
            ]

            if len(subset) > 0:
                # Compute success rate per (network_size, num_patterns)
                pivot = subset.groupby(['network_size', 'num_patterns']).agg(
                    success_rate=('recovered', 'mean')
                ).reset_index()
                pivot_table = pivot.pivot(
                    index='num_patterns',
                    columns='network_size',
                    values='success_rate'
                )
            else:
                pivot_table = pd.DataFrame()

            query_pivots[(corr, inf)] = pivot_table

    # Create figure
    fig_query, axes_query = plt.subplots(n_rows, n_cols, figsize=(16, 20), sharex=True, sharey=True)

    # Grey colormap for NaN (ineligible configs below 90% AR threshold)
