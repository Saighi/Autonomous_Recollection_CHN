def find_max_capacity(success_rates_df, network_size, threshold):
    """
    Find the maximum number of patterns where success rate >= threshold.
    """
    subset = success_rates_df[success_rates_df['network_size'] == network_size]
    successful = subset[subset['success_rate'] >= threshold]
    if len(successful) == 0:
        return 0
    return successful['num_patterns'].max()


